const assert = require("node:assert/strict");

module.exports = function validateExam(player, folder, cfg) {
  let page = player(folder);
  const action = (p, name) => p.context.document.querySelector(`[data-action="${name}"]`).events.get("click")();
  const json = (p, expression) => JSON.parse(p.run(`JSON.stringify(${expression})`));
  assert.equal(page.context.document.querySelector("#exam-count"), null, `${folder}: practice home has no exam controls`);
  assert.equal(page.context.document.querySelector("[data-exam-timer]"), null, `${folder}: practice remains untimed`);
  assert.equal(page.timers.size, 0, `${folder}: practice does not run an exam timer`);
  assert.ok(page.app.innerHTML.includes('href="exam.html"'), `${folder}: practice home links to the standalone Mock Exam page`);
  const source = page.run("JSON.stringify(window.QUIZ_QUESTIONS)");
  const id = page.run("questions.find(q => !q.ungraded).id");
  page.run(`start('all', ${id}); state.picked = current().acceptAny ? [current().answer[0]] : current().answer.slice(); check(); go(1); toggle(current().options[0].id)`);
  action(page, "home");
  const practice = page.run("JSON.stringify({results:state.results,drafts:state.drafts,orders:state.optionOrders,resume:state.resume})");
  const resultsStorage = page.storage.get(cfg.storageKey);
  const sessionStorage = page.storage.get(`${cfg.storageKey}:session`);
  page = player(folder, {}, page.storage, "exam.html");
  assert.equal(page.run("state.view"), "exam-setup", `${folder}: exam.html opens directly at Mock Exam setup`);
  assert.ok(page.context.document.title.startsWith("Mock Exam —"), `${folder}: standalone page has a descriptive title`);
  assert.equal(page.context.document.querySelector("#exam-count").value, "60", `${folder}: exam size defaults to 60`);
  assert.equal(page.context.document.querySelector("#exam-minutes").value, String(cfg.examMinutes), `${folder}: duration defaults to the quiz's configured limit`);
  const input = page.context.document.querySelector("#exam-count");
  input.value = "60";
  input.events.get("input")();
  page.context.document.querySelector(".exam-setup-form").events.get("submit")({preventDefault(){}});
  assert.equal(page.run("state.mode"), "exam", `${folder}: home form starts an exam`);
  const ids = json(page, "state.ids");
  assert.equal(ids.length, 60, `${folder}: exactly N questions`);
  assert.equal(new Set(ids).size, 60, `${folder}: no repeated questions`);
  assert.ok(page.run("pool().every(q => !q.ungraded)"), `${folder}: unscored items are excluded`);
  assert.notDeepEqual(ids, [...ids].sort((a,b)=>a-b), `${folder}: question order is shuffled`);
  assert.equal(page.run("Object.keys(state.results).length"), 0, `${folder}: earlier practice answers do not pre-answer an exam`);
  assert.ok(!page.app.innerHTML.includes(`<strong>${cfg.title}</strong>`), `${folder}: active exam is not labeled as practice`);
  assert.ok(page.app.innerHTML.includes('aria-label="Mock exam progress"'), `${folder}: exam progress has the correct accessible name`);
  assert.ok(page.app.innerHTML.includes('class="qnum" tabindex="-1">Question 1</h1>'), `${folder}: exam heading starts at Question 1`);
  const navLabels = [...page.app.innerHTML.matchAll(/data-jump="\d+"[^>]*aria-label="Question (\d+):/g)].map(m => Number(m[1]));
  assert.deepEqual(navLabels, Array.from({length:60}, (_,i)=>i+1), `${folder}: navigator numbers are 1 through N`);
  const jumpInput = page.context.document.querySelector("#question-number");
  jumpInput.value = "60";
  page.context.document.querySelector(".jump-form").events.get("submit")({preventDefault(){}});
  assert.equal(page.run("state.index"), 59, `${folder}: jump field uses exam position instead of source ID`);
  assert.ok(page.app.innerHTML.includes('class="qnum" tabindex="-1">Question 60</h1>'), `${folder}: last question is numbered N`);
  page.context.document.querySelector("#question-number").value = "61";
  page.context.document.querySelector(".jump-form").events.get("submit")({preventDefault(){}});
  assert.equal(page.run("state.index"), 59, `${folder}: out-of-range exam jump is rejected`);
  assert.ok(page.run("state.jumpError.includes('1 to 60')"), `${folder}: jump error uses the exam range`);
  page.run("jump(0)");
  assert.ok(!page.app.innerHTML.includes('class="explain ') && !page.app.innerHTML.includes('class="option-status"'), `${folder}: explanations and correctness stay hidden`);
  page.run("state.picked = current().acceptAny ? [current().answer[0]] : current().answer.slice(); rememberDraft(); check()");
  assert.equal(page.run("state.index"), 1, `${folder}: Save and next advances without grading`);
  assert.equal(page.run("Object.keys(state.results).length"), 0, `${folder}: saving an answer does not reveal correctness`);
  page.run("toggle(current().options[0].id)");
  const orders = page.run("JSON.stringify(state.optionOrders)");
  const picked = json(page, "state.picked");
  assert.equal(page.storage.get(cfg.storageKey), resultsStorage, `${folder}: exam does not change stored practice results`);
  assert.equal(page.storage.get(`${cfg.storageKey}:session`), sessionStorage, `${folder}: exam does not replace practice drafts or resume`);
  action(page, "home");
  assert.equal(page.run("JSON.stringify({results:state.results,drafts:state.drafts,orders:state.optionOrders,resume:state.resume})"), practice, `${folder}: leaving an exam restores regular practice`);
  assert.ok(page.app.innerHTML.includes('data-action="resume-exam"'), `${folder}: home offers a saved exam`);
  const reopened = player(folder, {}, page.storage, "exam.html");
  action(reopened, "resume-exam");
  assert.deepEqual(json(reopened, "state.ids"), ids, `${folder}: reopening restores the same sampled questions and order`);
  assert.equal(reopened.run("JSON.stringify(state.optionOrders)"), orders, `${folder}: reopening restores shuffled choices`);
  assert.deepEqual(json(reopened, "state.picked"), picked, `${folder}: reopening restores the current selection`);
  assert.equal(reopened.run("state.index"), 1, `${folder}: reopening restores the current position`);
  action(reopened, "home");
  const saved = reopened.run("JSON.stringify(state.examAttempt)");
  for (const value of ["", "0", "-1", "1.5", "abc", "100000"]) {
    const count = reopened.context.document.querySelector("#exam-count");
    count.value = value;
    count.events.get("input")();
    reopened.context.document.querySelector(".exam-setup-form").events.get("submit")({preventDefault(){}});
    assert.ok(reopened.run("state.examError.length > 0"), `${folder}: invalid count ${value} is explained`);
    assert.equal(reopened.run("JSON.stringify(state.examAttempt)"), saved, `${folder}: invalid count does not replace the saved attempt`);
  }

  const base = {section:cfg.sections[0].id, focus:cfg.focus[0].id, group:cfg.groups[0].id};
  const fixture = [
    { ...base,id:800,stem:["Single-answer question."],choices:["One","Two","Three"],answer:"B",why:"Why the second choice works.",wrong:{A:"First is incorrect.",C:"Third is incorrect."},notes:["Single answer notes."] },
    { ...base,id:801,stem:["Multiple-answer question."],choices:["One","Two","Three"],answer:"A,C",type:"multi",choose:2,why:"Two choices are needed.",wrong:{B:"Second is incorrect."},notes:["Multi-answer notes."] },
    { ...base,id:802,stem:["Equivalent-answer question."],choices:["One","Two","Three"],answer:"A,B",type:"single",acceptAny:true,why:"Either alternative works.",wrong:{C:"Third is incorrect."},notes:["One choice only."] },
    { ...base,id:803,stem:["Skipped question."],choices:["One","Two"],answer:"A",why:"First works.",wrong:{B:"Second is incorrect."},notes:["Skipped question notes."] },
    { ...base,id:804,stem:["Unresolved question."],choices:["One","Two"],answer:"",ungraded:true,why:"Unresolved.",wrong:{},notes:["Unscored notes."] },
  ];
  const config = {...cfg,storageKey:`${cfg.storageKey}:exam-check`};
  const setup = `window.Quiz.start(${JSON.stringify(config)}, ${JSON.stringify(fixture)})`;
  const exam = player(folder, {}, undefined, "exam.html");
  exam.run(setup);
  assert.equal(exam.context.document.querySelector("#exam-count").value, "4", `${folder}: a small pool defaults to its available scored count`);
  assert.ok(exam.app.innerHTML.includes("4 by default. Choose 1–4.") && exam.app.innerHTML.includes("4 questions by default"), `${folder}: setup guidance agrees with the actual small-pool default`);
  const reviewOnly = player(folder, {}, undefined, "exam.html");
  reviewOnly.run(`window.Quiz.start(${JSON.stringify(config)}, ${JSON.stringify([fixture[4]])})`);
  assert.equal(reviewOnly.context.document.querySelector("#exam-count"), null, `${folder}: an unscored-only pool has no impossible count input`);
  assert.ok(reviewOnly.app.innerHTML.includes("No scored questions available") && reviewOnly.app.innerHTML.includes("Review in practice"), `${folder}: an unscored-only pool explains the next action`);
  exam.run("state.results={800:{picked:['B'],status:'correct'}}; saveResults(); saveSession(); Math.random = () => 0; startRandomExam(4)");
  const originalIds = json(exam, "state.ids");
  assert.deepEqual([...originalIds].sort((a,b)=>a-b), [800,801,802,803], `${folder}: selecting the full eligible pool includes every scored item once`);
  exam.run("jump(state.ids.indexOf(800)); toggle('B'); check()");
  exam.run("jump(state.ids.indexOf(801)); toggle('A')");
  assert.ok(!exam.run("canCheck(current())"), `${folder}: incomplete multi-selection cannot use Save and next`);
  const next = exam.run("nextUnansweredIndex()");
  assert.notEqual(exam.run(`state.ids[${next}]`), 800, `${folder}: next unanswered skips a completed selection without needing grades`);
  exam.run("jump(state.ids.indexOf(802))");
  assert.ok(exam.app.innerHTML.includes("Choose 1 answer. Selections save automatically."), `${folder}: equivalent single-answer choices still request just one selection`);
  assert.ok(exam.context.document.querySelector('[data-action="check"]').disabled, `${folder}: an empty equivalent-answer selection cannot continue`);
  exam.run("toggle('B')");
  assert.ok(exam.app.innerHTML.includes("Selection saved. You can change it before submitting."), `${folder}: one equivalent answer completes the selection`);
  assert.ok(!exam.context.document.querySelector('[data-action="check"]').disabled, `${folder}: one equivalent answer enables Save and next`);
  exam.run("showSummary()");
  assert.ok(exam.app.innerHTML.includes("2 of 4 questions have a complete selection"), `${folder}: pre-submit review identifies incomplete and skipped items`);
  assert.deepEqual([...exam.app.innerHTML.matchAll(/<strong>Question (\d+)<\/strong>/g)].map(m=>Number(m[1])), [1,2,3,4], `${folder}: exam review rows use 1–N numbering`);
  assert.ok(!exam.app.innerHTML.includes('class="explain ') && !exam.app.innerHTML.includes("Score:"), `${folder}: pre-submit review does not leak results`);
  action(exam, "submit-exam");
  assert.equal(exam.run("state.results[800].status"), "correct", `${folder}: single-answer grading`);
  assert.equal(exam.run("state.results[801].status"), "wrong", `${folder}: partial multi-selection is incorrect`);
  assert.equal(exam.run("state.results[802].status"), "correct", `${folder}: equivalent answer is accepted`);
  assert.equal(exam.run("state.results[803].status"), "unanswered", `${folder}: skipped item is recorded separately`);
  assert.ok(exam.app.innerHTML.includes("Score: 50%"), `${folder}: score includes skipped questions in the denominator`);
  const result = exam.run("JSON.stringify(state.results)");
  exam.context.document.querySelector(`[data-jump="${exam.run("state.ids.indexOf(800)")}"]`).events.get("click")();
  assert.ok(exam.app.innerHTML.includes('class="explain ') && !exam.app.innerHTML.includes('data-action="retry"'), `${folder}: submitted answer review reveals explanations and is read-only`);
  exam.run("toggle('A'); retry(); clearSelection(); submitExam()");
  assert.equal(exam.run("JSON.stringify(state.results)"), result, `${folder}: submitted results cannot be changed through answer controls`);
  exam.run("jump(state.ids.indexOf(803))");
  assert.ok(exam.app.innerHTML.includes("Your answer: Not answered"), `${folder}: skipped answer review is clear`);
  action(exam, "home");
  assert.equal(exam.run("state.results[800].status"), "correct", `${folder}: practice result survives submission`);
  const submitted = player(folder, {}, exam.storage, "exam.html");
  submitted.run(setup);
  action(submitted, "resume-exam");
  assert.equal(submitted.run("state.view"), "summary", `${folder}: submitted attempt reopens at results`);
  assert.ok(submitted.app.innerHTML.includes("Score: 50%"), `${folder}: score persists after reopening`);
  submitted.run("start('all')");
  assert.equal(submitted.run("state.mode"), "practice", `${folder}: regular practice can restart after exam review`);
  assert.equal(submitted.run("state.results[800].status"), "correct", `${folder}: starting practice retains its own results`);
  submitted.run("startRandomExam(1)");
  assert.equal(submitted.run("state.ids.length"), 1, `${folder}: a custom one-question attempt is supported`);
  action(submitted, "home");
  const regularResult = submitted.run("JSON.stringify(state.results)");
  action(submitted, "clear-exam");
  assert.equal(submitted.run("state.examAttempt"), null, `${folder}: Clear saved attempt clears the saved exam`);
  assert.equal(submitted.run("JSON.stringify(state.results)"), regularResult, `${folder}: clearing an exam preserves regular practice results`);
  assert.ok(!submitted.storage.has(`${config.storageKey}:exam`), `${folder}: cleared exam is removed from storage`);
  const invalidStorage = new Map([[`${config.storageKey}:exam`, JSON.stringify({ids:[800,800],drafts:{},index:0})]]);
  const invalid = player(folder, {}, invalidStorage, "exam.html");
  invalid.run(setup);
  assert.equal(invalid.run("state.examAttempt"), null, `${folder}: a corrupted duplicate-question attempt is rejected`);
  invalid.storage.set(`${config.storageKey}:exam`, JSON.stringify({ids:[804],drafts:{},index:0}));
  invalid.run(setup);
  assert.equal(invalid.run("state.examAttempt"), null, `${folder}: a saved attempt containing an unscored question is rejected`);
  invalid.run("startRandomExam(2)");
  invalid.context.localStorage.setItem = () => { throw Error("Storage disabled"); };
  invalid.run("toggle(current().options[0].id)");
  assert.ok(invalid.run("state.storageIssue") && invalid.app.innerHTML.includes("Progress could not be saved"), `${folder}: exam save failures are visible and do not stop the attempt`);
  const stale = player(folder, {}, undefined, "exam.html");
  stale.run(setup);
  const newerPractice = JSON.stringify({filter:"all",id:801,drafts:{801:["A","C"]},optionOrders:{}});
  stale.storage.set(`${config.storageKey}:session`, newerPractice);
  stale.run("startRandomExam(2)");
  action(stale, "home");
  assert.equal(stale.storage.get(`${config.storageKey}:session`), newerPractice, `${folder}: exam activity in a stale tab cannot overwrite newer practice selections`);
  const savedExam = stale.storage.get(`${config.storageKey}:exam`);
  const clearPractice = player(folder, {}, stale.storage);
  clearPractice.run(`${setup}; resetAll()`);
  assert.equal(clearPractice.storage.get(`${config.storageKey}:exam`), savedExam, `${folder}: clearing practice preserves the saved exam`);
  assert.equal(page.run("JSON.stringify(window.QUIZ_QUESTIONS)"), source, `${folder}: sampling does not alter quiz data`);

  // Advance a fake wall clock and invoke the scheduled tick; no real waiting.
  const timed = player(folder, {}, undefined, "exam.html");
  timed.run(setup);
  const clockStart = Date.now();
  timed.run(`Date.now = () => ${clockStart}`);
  for (const value of ["", "0", "-1", "1.5", "abc", "1441"]) {
    const minutes = timed.context.document.querySelector("#exam-minutes");
    minutes.value = value;
    minutes.events.get("input")();
    timed.context.document.querySelector(".exam-setup-form").events.get("submit")({preventDefault(){}});
    assert.ok(timed.run("state.examTimeError.length > 0"), `${folder}: invalid duration ${value} is explained`);
    assert.equal(timed.run("state.examAttempt"), null, `${folder}: invalid duration cannot start an attempt`);
    assert.equal(timed.effects.focused, "#exam-minutes", `${folder}: duration error receives focus`);
  }
  const minuteInput = timed.context.document.querySelector("#exam-minutes");
  minuteInput.value = "10";
  minuteInput.events.get("input")();
  timed.context.document.querySelector(".exam-setup-form").events.get("submit")({preventDefault(){}});
  const deadline = clockStart + 600000;
  assert.equal(timed.run("state.examAttempt.deadlineAt"), deadline, `${folder}: custom duration creates a fixed deadline`);
  assert.equal(timed.context.document.querySelector("[data-exam-time]").textContent, "00:10:00", `${folder}: initial countdown is visible`);
  assert.equal(timed.timers.size, 1, `${folder}: one timer is scheduled`);
  timed.run("jump(state.ids.indexOf(800)); toggle('B'); jump(state.ids.indexOf(801)); toggle('A')");
  const reader = timed.context.document.querySelector(".panel-body");
  reader.scrollTop = 240;
  timed.run(`Date.now = () => ${clockStart + 300000}`);
  [...timed.timers.values()][0]();
  assert.equal(timed.context.document.querySelector("[data-exam-time]").textContent, "00:05:00", `${folder}: countdown derives from the deadline`);
  assert.ok(timed.context.document.querySelector("[data-exam-timer]").className.includes("warning"), `${folder}: five-minute warning`);
  assert.ok(timed.context.document.querySelector("[data-exam-timer-alert]").textContent.includes("Five minutes"), `${folder}: warning is announced accessibly`);
  assert.equal(timed.context.document.querySelector(".panel-body"), reader, `${folder}: ticks do not replace the reader or its focus/scroll`);
  assert.equal(reader.scrollTop, 240, `${folder}: ticking preserves reader position`);
  timed.run("showSummary()");
  assert.ok(timed.context.document.querySelector("[data-exam-time]"), `${folder}: pre-submission review keeps the countdown visible`);
  assert.equal(timed.timers.size, 1, `${folder}: navigation does not create duplicate intervals`);
  action(timed, "home");
  assert.equal(timed.run("state.examAttempt.deadlineAt"), deadline, `${folder}: Save & exit does not pause the timer`);
  assert.ok(timed.context.document.querySelector("[data-exam-time]"), `${folder}: saved-attempt card shows time remaining`);
  const timerResume = player(folder, {}, timed.storage, "exam.html");
  timerResume.run(setup);
  timerResume.run(`Date.now = () => ${deadline - 60000}`);
  action(timerResume, "resume-exam");
  assert.equal(timerResume.run("state.examAttempt.deadlineAt"), deadline, `${folder}: reload/resume cannot reset the deadline`);
  assert.equal(timerResume.run("state.examAttempt.durationMinutes"), 10, `${folder}: custom duration survives reload`);
  [...timerResume.timers.values()][0]();
  assert.equal(timerResume.context.document.querySelector("[data-exam-time]").textContent, "00:01:00", `${folder}: resumed countdown includes time away`);
  assert.ok(timerResume.context.document.querySelector("[data-exam-timer]").className.includes("critical"), `${folder}: last-minute warning`);
  timerResume.run(`Date.now = () => ${deadline + 8000}`);
  [...timerResume.timers.values()][0]();
  assert.ok(timerResume.run("state.examAttempt.submitted && state.examAttempt.timedOut"), `${folder}: expiry automatically submits`);
  assert.equal(timerResume.run("state.view"), "summary", `${folder}: expiry opens results`);
  assert.equal(timerResume.run("state.examAttempt.submittedAt"), deadline, `${folder}: background delays do not extend time used`);
  assert.equal(timerResume.run("state.results[800].status"), "correct", `${folder}: expiry keeps completed answers`);
  assert.equal(timerResume.run("state.results[801].status"), "wrong", `${folder}: expiry grades incomplete multi-selections as incorrect`);
  assert.equal(timerResume.run("state.results[803].status"), "unanswered", `${folder}: expiry retains skipped questions`);
  assert.ok(timerResume.app.innerHTML.includes("Time is up.") && timerResume.app.innerHTML.includes("Score: 25%"), `${folder}: automatic-submission result is explicit`);
  assert.equal(timerResume.timers.size, 0, `${folder}: submitted attempt stops ticking`);
  const finalResults = timerResume.run("JSON.stringify(state.results)");
  timerResume.run("toggle('A'); clearSelection(); submitExam(); updateExamTimer()");
  assert.equal(timerResume.run("JSON.stringify(state.results)"), finalResults, `${folder}: automatic submission locks answers`);

  const late = player(folder, {}, undefined, "exam.html");
  late.run(`${setup}; Date.now = () => ${clockStart}; startRandomExam(1, 1)`);
  late.run(`Date.now = () => ${clockStart + 60001}; toggle(current().answer[0])`);
  assert.ok(late.run("state.examAttempt.timedOut"), `${folder}: a late click submits even before the next tick`);
  assert.equal(late.run("state.picked.length"), 0, `${folder}: a late answer cannot sneak into the result`);
  const reviewing = player(folder, {}, undefined, "exam.html");
  reviewing.run(`${setup}; Date.now = () => ${clockStart}; startRandomExam(1, 1); showSummary(); Date.now = () => ${clockStart + 60001}`);
  reviewing.events.get("visibilitychange")();
  assert.ok(reviewing.run("state.examAttempt.timedOut"), `${folder}: returning to an overdue review screen submits immediately`);
  assert.equal(reviewing.timers.size, 0, `${folder}: review-screen expiry clears the interval`);
  const overdue = json(timed, "state.examAttempt");
  overdue.startedAt = clockStart - 1200000;
  overdue.deadlineAt = overdue.startedAt + overdue.durationMinutes * 60000;
  const overdueStorage = new Map([[`${config.storageKey}:exam`, JSON.stringify(overdue)]]);
  const expiredClosed = player(folder, {}, overdueStorage, "exam.html");
  expiredClosed.run(setup);
  assert.ok(expiredClosed.run("state.examAttempt.submitted && state.examAttempt.timedOut"), `${folder}: reopening after the deadline submits the saved attempt`);
  assert.equal(expiredClosed.run("state.mode"), "practice", `${folder}: expiry on setup does not replace practice state`);
  assert.ok(expiredClosed.app.innerHTML.includes("Time expired · Auto-submitted"), `${folder}: setup explains an expired saved attempt`);
  action(expiredClosed, "resume-exam");
  assert.ok(expiredClosed.app.innerHTML.includes("Score: 25%"), `${folder}: expired saved attempt opens at its result`);
  const practiceAtExit = timed.run("JSON.stringify(state.results)");
  timed.run(`Date.now = () => ${deadline + 8000}`);
  timed.events.get("focus")();
  assert.ok(timed.run("state.examAttempt.timedOut"), `${folder}: saved attempt expires while the setup page is open`);
  assert.equal(timed.run("state.view"), "exam-setup", `${folder}: setup expiry keeps the setup page open`);
  assert.equal(timed.run("JSON.stringify(state.results)"), practiceAtExit, `${folder}: setup expiry cannot alter practice results`);
  assert.equal(timed.timers.size, 0, `${folder}: setup expiry clears the interval`);

  const early = player(folder, {}, undefined, "exam.html");
  early.run(`${setup}; Date.now = () => ${clockStart}; startRandomExam(1, 10); toggle(current().answer[0])`);
  early.run(`Date.now = () => ${clockStart + 65000}; submitExam()`);
  assert.ok(!early.run("state.examAttempt.timedOut"), `${folder}: manual submission remains distinct from expiry`);
  assert.ok(early.app.innerHTML.includes("00:01:05") && early.app.innerHTML.includes("00:10:00"), `${folder}: results show elapsed time against the limit`);
  early.run(`Date.now = () => ${deadline + 8000}; updateExamTimer()`);
  assert.equal(early.run("state.examAttempt.submittedAt"), clockStart + 65000, `${folder}: manual submission freezes elapsed time`);
  assert.equal(early.timers.size, 0, `${folder}: manual submission clears the interval`);

  const old = { ids:overdue.ids, drafts:overdue.drafts, optionOrders:overdue.optionOrders, index:overdue.index, submitted:false };
  const legacy = player(folder, {}, new Map([[`${config.storageKey}:exam`, JSON.stringify(old)]]), "exam.html");
  legacy.run(setup);
  assert.ok(legacy.app.innerHTML.includes("timer when you resume"), `${folder}: older untimed attempts explain migration`);
  action(legacy, "resume-exam");
  assert.equal(legacy.run("state.examAttempt.durationMinutes"), cfg.examMinutes, `${folder}: older attempt receives the default duration once`);
  assert.deepEqual(json(legacy, "state.drafts"), old.drafts, `${folder}: timer migration preserves existing selections`);
  const migratedDeadline = legacy.run("state.examAttempt.deadlineAt");
  action(legacy, "home");
  action(legacy, "resume-exam");
  assert.equal(legacy.run("state.examAttempt.deadlineAt"), migratedDeadline, `${folder}: repeated resumes do not restart a migrated timer`);
  console.log(`PASS timer ${folder}: default/custom limits, input errors, live countdown, warnings, scroll stability, deadline persistence, active/closed expiry, late-answer lock, manual timing and legacy resume`);
  console.log(`PASS mock exam ${folder}: standalone page, 1–N numbering/jumps/review, default/custom counts, scored sampling, isolated progress and resets, stale-tab safety, grading and resume`);
};
